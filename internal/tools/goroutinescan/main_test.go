func scanSrc(t *testing.T, src string) []Goroutine {
	t.Helper()
	fset := token.NewFileSet()
	gs, err := scanFileSource(fset, "test.go", []byte(src))
	if err != nil {
		t.Fatalf("scanFileSource: %v", err)
	}
	return gs
}

func TestScan_UnmanagedGoroutine(t *testing.T) {
	gs := scanSrc(t, `package p
func Worker() {
	go doWork()
}
func doWork() {}
`)
	if len(gs) != 1 {
		t.Fatalf("want 1 goroutine, got %d: %+v", len(gs), gs)
	}
	g := gs[0]
	if g.Managed {
		t.Errorf("want unmanaged, got managed; signals=%v", g.Signals)
	}
	if g.Func != "Worker" {
		t.Errorf("want func Worker, got %q", g.Func)
	}
	if len(g.Signals) != 0 {
		t.Errorf("want no signals, got %v", g.Signals)
	}
}

func TestScan_WaitGroupManaged(t *testing.T) {
	gs := scanSrc(t, `package p
import "sync"
func Run() {
	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()
		work()
	}()
	wg.Wait()
}
func work() {}
`)
	if len(gs) != 1 {
		t.Fatalf("want 1, got %d", len(gs))
	}
	if !gs[0].Managed {
		t.Errorf("want managed via waitgroup, signals=%v", gs[0].Signals)
	}
}

