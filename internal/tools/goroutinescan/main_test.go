func TestScanDir_SkipsTestAndGenerated(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("prod.go", "package p\nfunc F() { go g() }\nfunc g() {}\n")
	write("prod_test.go", "package p\nimport \"testing\"\nfunc TestX(t *testing.T) { go g2() }\nfunc g2() {}\n")
	write("gen.go", "// Code generated by tool. DO NOT EDIT.\npackage p\nfunc H() { go g3() }\nfunc g3() {}\n")

	gs, err := scanDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(gs) != 1 {
		t.Fatalf("want 1 (only prod.go), got %d: %+v", len(gs), gs)
	}
	if !strings.HasSuffix(gs[0].File, "prod.go") {
		t.Errorf("want prod.go, got %s", gs[0].File)
	}
}

func TestRun_EmitsDeterministicJSON(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "a.go"),
		[]byte("package p\nfunc F() { go x() }\nfunc x() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	var b1, b2 bytes.Buffer
	if err := run(config{Root: dir, Out: &b1}); err != nil {
		t.Fatal(err)
	}
	if err := run(config{Root: dir, Out: &b2}); err != nil {
		t.Fatal(err)
	}
	if b1.String() != b2.String() {
		t.Errorf("non-deterministic output:\n%s\n---\n%s", b1.String(), b2.String())
	}
	var res Result
	if err := json.Unmarshal(b1.Bytes(), &res); err != nil {
		t.Fatalf("invalid JSON: %v", err)
	}
	if res.Schema != schemaVersion {
		t.Errorf("schema=%q want %q", res.Schema, schemaVersion)
	}
	if res.Summary.Total != 1 || res.Summary.Unmanaged != 1 {
		t.Errorf("summary=%+v want total=1 unmanaged=1", res.Summary)
	}
	// Regression: an unmanaged goroutine must emit "signals": [] (not null),
	// or downstream jq/aggregation chokes on a null array.
	if strings.Contains(b1.String(), `"signals": null`) {
		t.Errorf("signals must serialize as [] not null:\n%s", b1.String())
	}
}
